// Regenerates test/vscode-builtin-languages.json: the file extensions claimed by the languages that ship
// with VS Code. The tests use it because a built-in language that claims the same extension as this
// extension wins (for example XML claims .mod), so such files can only be reached through detect.json.
//
//   node test/update-builtin-languages.js "/Applications/Visual Studio Code.app"
const fs = require('fs');
const path = require('path');

const app = process.argv[2];
if (!app) { console.error('Usage: node test/update-builtin-languages.js <VS Code installation folder>'); process.exit(2); }
const candidates = [path.join(app, 'Contents', 'Resources', 'app'), path.join(app, 'resources', 'app'), app];
const appDir = candidates.find((d) => fs.existsSync(path.join(d, 'extensions')));
if (!appDir) { console.error('No extensions folder found under ' + app); process.exit(1); }

const map = {};
const extDir = path.join(appDir, 'extensions');
for (const name of fs.readdirSync(extDir).sort()) {
  const file = path.join(extDir, name, 'package.json');
  if (!fs.existsSync(file)) continue;
  const pkg = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const lang of (pkg.contributes && pkg.contributes.languages) || []) {
    for (const ext of lang.extensions || []) map[ext.toLowerCase()] = lang.id;
  }
}
const version = JSON.parse(fs.readFileSync(path.join(appDir, 'package.json'), 'utf8')).version;
const sorted = {};
for (const k of Object.keys(map).sort()) sorted[k] = map[k];
const out = { _comment: 'Generated by test/update-builtin-languages.js from VS Code ' + version, extensions: sorted };
fs.writeFileSync(path.join(__dirname, 'vscode-builtin-languages.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`${Object.keys(sorted).length} extensions from VS Code ${version}`);
